const nfc = (s: string) => s.normalize("NFC");

/** 시군구명(NFC) → 시도 정식명(sidoRegions 기반, 최초 등장 우선). */
const SIDO_BY_SIGUNGU = new Map<string, string>();
for (const sido of REGIONS) {
  for (const sg of sido.sigungu) {
    if (!SIDO_BY_SIGUNGU.has(nfc(sg.name))) SIDO_BY_SIGUNGU.set(nfc(sg.name), sido.label);
  }
}

/** 광역시·특별시 짧은 접두("광주 광산구") → 시도 정식명. */
