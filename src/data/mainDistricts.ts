import { regions, getRegionById } from "@/data/regions";

/** 기존 122 + 생활권 94 = /[region] 랜딩 전체. */
export const allLandingRegions: Region[] = [...regions, ...mainDistricts];

const districtById = new Map(mainDistricts.map((r) => [r.id, r]));

/** id 로 랜딩 지역 조회(기존 regions 우선, 없으면 생활권). */
export function getLandingRegion(id: string): Region | undefined {
  return getRegionById(id) ?? districtById.get(id);
}
