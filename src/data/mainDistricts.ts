/** 시도 정식명 → 짧은 표기(regions.ts province 규칙과 정합). */
const SHORT_SIDO: Record<string, string> = {
  서울특별시: "서울", 부산광역시: "부산", 대구광역시: "대구", 인천광역시: "인천",
  광주광역시: "광주", 대전광역시: "대전", 울산광역시: "울산", 세종특별자치시: "세종",
  경기도: "경기", 강원도: "강원", 강원특별자치도: "강원", 충청북도: "충북", 충청남도: "충남",
  전라북도: "전북", 전북특별자치도: "전북", 전라남도: "전남", 경상북도: "경북",
  경상남도: "경남", 제주특별자치도: "제주",
};

/** 소속 시군구 → 짧은 시도 표기(미해석 시 소속 시군구 그대로). */
function resolveProvince(sigungu: string): string {
  const parts = sigungu.split(" ");
  const full =
    (parts.length >= 2 && SIDO_BY_METRO[parts[0]]) ||
    SIDO_BY_SIGUNGU.get(nfc(sigungu)) ||
    SIDO_BY_SIGUNGU.get(nfc(parts[0])) ||
    SIDO_FALLBACK[sigungu] ||
    "";
  // 미해석 시에도 빈 문자열 노출 금지 — 소속 시군구를 그대로 상위표시로 사용.
  if (!full) return sigungu;
  return SHORT_SIDO[full] ?? full;
}

/** 생활권 → /[region] Region. id=name=지명, cityQuery=소속 시군구, province=짧은 시도. */
export const mainDistricts: Region[] = RAW.map(([name, sigungu]) => ({
  id: name,
  province: resolveProvince(sigungu),
  cityQuery: sigungu,
  name,
}));

