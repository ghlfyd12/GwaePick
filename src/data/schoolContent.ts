/**
 * 학교급(초·중·고) × 과목 조합별 고유 콘텐츠 — 페이지 간 유사도를 낮추기 위한 변주 데이터.
 *
 * 구조: schoolContent[level][subjectSlug] = 변형 3개 배열.
 *   - level: "elem"(초) | "middle"(중) | "high"(고)
 *   - subjectSlug: subjects.ts 의 slug 8종(korean/english/math/social/science/history/essay/coding)
 *   - 변형 선택은 lib/contentVariant.ts 에서 학교 slug 해시로 결정론적으로 고른다.
 *
 * 톤 규칙(반드시 준수):
 *   - 차분한 동료 교사. 과장·영업 어투·느낌표 금지. 성적 보장·단정 금지("관리합니다" 수준까지만).
 *   - 지칭은 "선생님/관리/지도/상담"으로 통일한다(영업성 대체 호칭 금지).
 *   - 실존 학교의 출제 경향·난이도·일정을 단정하지 않는다. 학교명은 {school} 슬롯으로만 넣는다.
 *   - 학교급별 시험 체계 반영: 초등=단원평가·수행평가·기초 습관(내신/중간/기말 금지),
 *     중등=중간·기말 내신·수행평가·자유학기 이후 첫 시험, 고등=내신 등급·지필/수행 병행·모의고사와 내신 균형.
 *     코딩은 전 학교급에서 지필 프레이밍 금지 — 정보 교과 수행평가·프로젝트·흥미 유지 관점.
 */

export interface SchoolContentVariant {
  struggles: {
    /** {school} 슬롯을 포함할 수 있는 도입 문장. */
    intro: string;
    /** 이 학교급×과목 학생이 자주 겪는 어려움 3~4개. */
    items: string[];
  };
  examPrep: {
    /** 섹션 제목(예: "중간·기말 3주 전, 이렇게 관리합니다"). */
    title: string;
    /** 2~3개 문단. {school} 슬롯 사용 가능. */
    paragraphs: string[];
    /** 관리 단계 3~4개(진단 → 계획 → 점검 흐름). */
    steps: string[];
  };
}

