/** levelFocus 표기에서 급별 응시 자격 사실을 파생. */
const factFor = (levelFocus: string): string => {
  const hasCho = levelFocus.includes("초졸");
  const hasJung = levelFocus.includes("중졸");
  const hasGo = levelFocus.includes("고졸");
  if (hasCho && hasJung) return `${F_CHOJOL} ${F_JUNGJOL}`;
  if (hasGo) return F_GOJOL;
  if (hasJung) return F_JUNGJOL;
  return F_CHOJOL;
};

